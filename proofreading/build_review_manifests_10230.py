def flatten(payload):
    return [seg for chapter in payload.get("chapters", []) for seg in chapter.get("segments", [])]


def normalized_target(old: str, idx: int) -> str:
    target = old.replace("吉川诺艾尔", "诺艾尔").replace("诺艾尔她", "诺艾尔")
    return CORRECTIONS.get(idx, target)


def main() -> None:
    data = json.loads(CANON.read_text(encoding="utf-8-sig"))
    segs = flatten(data)
    if len(segs) < END:
        raise RuntimeError(f"canonical has only {len(segs)} segments")

    total = 0
    for start in range(START, END + 1, 100):
        end = min(start + 99, END)
        entries = []
        for idx in range(start, end + 1):
            old = str(segs[idx - 1].get("target", ""))
            new = normalized_target(old, idx)
            if new != old:
                entries.append({
                    "index": idx,
                    "new_target": new,
                    "status": "corrected",
                    "note": "人工校对。",
                })
        payload = {
            "range": {"start": start, "end": end},
            "reviewed_at": REVIEWED_AT,
            "format": "compact-v1",
            "entries": entries,
        }
        out = PROOF / f"reviewed-batch-{start:06d}-{end:06d}.json"
        out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"{out.name}: {len(entries)} corrections")
        total += len(entries)
    print(f"TOTAL_CORRECTIONS={total}")


if __name__ == "__main__":
    main()
